-- Baseline schema. Flyway owns every schema change from this point on;
-- Hibernate DDL generation stays off (spring.jpa.hibernate.ddl-auto=validate).
--
-- Portable DDL only: this script must run unchanged on H2 (default profile)
-- and PostgreSQL (postgres profile). Do not introduce SERIAL, AUTO_INCREMENT,
-- or engine-specific types.
CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255),
    completed BOOLEAN NOT NULL
);
